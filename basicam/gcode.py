from __future__ import annotations

from dataclasses import dataclass

from basicam.operations import Operation
from basicam.setups import MachiningSetup
from basicam.stock_analysis import RoughingAnalysis


@dataclass(frozen=True)
class GCodeSettings:
    units_mode: str = "G21"  # G21 = mm, G20 = inches
    safe_z_mm: float = 5.0
    stock_top_z_mm: float = 0.0
    x_min_mm: float = 0.0
    x_max_mm: float = 100.0
    y_min_mm: float = 0.0
    y_max_mm: float = 80.0
    manual_spindle: bool = False
    recommended_rpm: int | None = None


def _emit_setup_operations(
    lines: list[str],
    setup: MachiningSetup,
    cfg: GCodeSettings,
    roughing: RoughingAnalysis | None,
) -> None:
    scale = (1.0 / 25.4) if cfg.units_mode.upper() == "G20" else 1.0

    def fmt(val_mm: float) -> str:
        return f"{val_mm * scale:.3f}"

    ox, oy, oz = setup.origin_mm
    lines.append(f"(=== SETUP: {setup.name} | Orientation: {setup.orientation} ===)")
    lines.append(
        f"(Setup origin ref: X{fmt(ox)} Y{fmt(oy)} Z{fmt(oz)} | Manual zero at controller)"
    )

    for op in setup.operations:
        is_finish = op.kind.casefold() == "finish"
        allowance_note = (
            f" | finish remainder: {roughing.finish_remainder_volume_mm3:.2f} mm3"
            if (is_finish and roughing is not None)
            else ""
        )
        lines.append(
            f"({op.name} | {op.kind} | {op.tool} | target: {op.target}{allowance_note})"
        )
        if cfg.manual_spindle:
            rec_note = f", recommended ~{cfg.recommended_rpm} RPM" if cfg.recommended_rpm else ""
            lines.append(f"(MANUAL SPINDLE: set dial to ~{int(op.rpm)} RPM{rec_note})")
        elif op.rpm > 0:
            lines.append(f"M3 S{int(op.rpm)}")

        final_z = oz + cfg.stock_top_z_mm - abs(op.depth_mm)
        step = abs(op.stepdown_mm) if op.stepdown_mm > 0 else abs(op.depth_mm)
        z_levels: list[float] = []
        current_z = oz + cfg.stock_top_z_mm
        while current_z - step > final_z + 1e-9:
            current_z -= step
            z_levels.append(current_z)
        if not z_levels or abs(z_levels[-1] - final_z) > 1e-9:
            z_levels.append(final_z)

        feed = max(float(op.feed_mm_min) * scale, 0.1)
        x0, x1 = fmt(ox + cfg.x_min_mm), fmt(ox + cfg.x_max_mm)
        y0, y1 = fmt(oy + cfg.y_min_mm), fmt(oy + cfg.y_max_mm)
        safe_z = fmt(oz + cfg.safe_z_mm)

        for z in z_levels:
            lines.append(f"G0 X{x0} Y{y0}")
            lines.append(f"G1 Z{fmt(z)} F{feed:.1f}")
            lines.append(f"G1 X{x1} Y{y0} F{feed:.1f}")
            lines.append(f"G1 X{x1} Y{y1}")
            lines.append(f"G1 X{x0} Y{y1}")
            lines.append(f"G1 X{x0} Y{y0}")
            lines.append(f"G0 Z{safe_z}")

        if not cfg.manual_spindle:
            lines.append("M5")


def generate_gcode(
    operations_or_setups: list[Operation] | list[MachiningSetup],
    settings: GCodeSettings | None = None,
    roughing: RoughingAnalysis | None = None,
) -> str:
    if not operations_or_setups:
        raise ValueError("At least one operation or setup is required to generate G-code.")

    if isinstance(operations_or_setups[0], MachiningSetup):
        setups = [s for s in operations_or_setups if isinstance(s, MachiningSetup) and s.operations]
        if not setups:
            raise ValueError("Add at least one operation before exporting G-code.")
    else:
        setups = [
            MachiningSetup(
                name="Setup 1",
                operations=[op for op in operations_or_setups if isinstance(op, Operation)],
            )
        ]

    cfg = settings or GCodeSettings()
    scale = (1.0 / 25.4) if cfg.units_mode.upper() == "G20" else 1.0

    def fmt(val_mm: float) -> str:
        return f"{val_mm * scale:.3f}"

    lines: list[str] = [
        "(Generated by BasiCAM CNC - prototype output; verify before machining)",
        "G90",
        cfg.units_mode.upper(),
    ]
    if roughing is not None:
        lines.append(
            f"(Roughing analysis: removed {roughing.rough_removal_volume_mm3:.2f} mm3, "
            f"finish remainder {roughing.finish_remainder_volume_mm3:.2f} mm3, "
            f"allowance {roughing.finish_allowance_mm:.3f} mm)"
        )
    lines.append(f"G0 Z{fmt(cfg.safe_z_mm)}")

    for idx, setup in enumerate(setups):
        _emit_setup_operations(lines, setup, cfg, roughing)
        if idx < len(setups) - 1:
            next_setup = setups[idx + 1]
            nox, noy, noz = next_setup.origin_mm
            lines.append(f"G0 Z{fmt(cfg.safe_z_mm)}")
            if not cfg.manual_spindle:
                lines.append("M5")
            lines.append("(--- SETUP STOP: Refixture/reorient part for next setup ---)")
            lines.append(
                f"(Next setup: {next_setup.name} | Orientation: {next_setup.orientation})"
            )
            lines.append(
                f"(ACTION REQUIRED: Re-zero XYZ at controller; ref origin X{fmt(nox)} Y{fmt(noy)} Z{fmt(noz)} before resuming)"
            )
            lines.append("M0")

    lines.append(f"G0 Z{fmt(cfg.safe_z_mm)}")
    lines.append(f"G0 X{fmt(0.0)} Y{fmt(0.0)}")
    lines.append("M30")
    return "\n".join(lines) + "\n"
